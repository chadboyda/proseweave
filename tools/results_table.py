#!/usr/bin/env python3
"""Generate validation/RESULTS.md from src/proseweave/data/validation.json.

    python3 tools/results_table.py            print
    python3 tools/results_table.py --write    replace validation/RESULTS.md
    python3 tools/results_table.py --check    exit 1 if RESULTS.md is out of date
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src" / "proseweave" / "data" / "validation.json"
OUT = ROOT / "validation" / "RESULTS.md"
RHO, LOWER = 0.80, 0.70


def cell(r):
    if not r or r.get("rho") is None:
        return "-"
    ok = r["rho"] >= RHO and r.get("lower90", 0) >= LOWER
    return f"{r['rho']:.2f} / {r.get('lower90', float('nan')):.2f}{'' if ok else ' (below)'}"


def render() -> str:
    v = json.loads(DATA.read_text())
    rows = [(x.get("family", "?"), k, x) for k, x in v.items() if x.get("family") != "construct"]
    rows.sort()
    n = len(rows)
    valid = sum(1 for _, _, x in rows if x.get("valid"))
    per = {c: sum(1 for _, _, x in rows if x.get(c) and x[c].get("rho", 0) >= RHO
                  and x[c].get("lower90", 0) >= LOWER) for c in ("private", "open")}
    out = ["# Results: single-text properties", "",
           "Rank agreement of each property with the reference outputs, on the article corpus",
           "(`articles/`) and the open corpus (`open/`). Rule and pass mark: `PROTOCOL.md`",
           f"(Spearman rho >= {RHO:.2f}, bootstrap 90% lower bound >= {LOWER:.2f}). A property is",
           "validated only if it passes on both corpora. Properties below the bar are still computed,",
           "but they are marked `valid: false` in `src/proseweave/data/validation.json`, which",
           "excludes them from `profile` and `compare`.", "",
           f"**{valid} of {n} single-text properties are validated** "
           f"(article corpus {per['private']}, open corpus {per['open']}).", "",
           "Generated by `tools/results_table.py`; do not edit by hand.", "",
           "| family | property | article corpus rho / lower90 | open corpus rho / lower90 | validated |",
           "|---|---|---|---|---|"]
    for fam, k, x in rows:
        out.append(f"| {fam} | `{k}` | {cell(x.get('private'))} | {cell(x.get('open'))} | "
                   f"{'yes' if x.get('valid') else 'no'} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--write" in sys.argv:
        OUT.write_text(text)
    elif "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    else:
        sys.stdout.write(text)
